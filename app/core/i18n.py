def get_translator(request):
    lang = request.cookies.get("language", "fr")
    if lang not in TRANSLATIONS:
        lang = "fr"

    def translate(key, **kwargs):
        text = TRANSLATIONS[lang].get(key, key)
        if kwargs:
            return text.format(**kwargs)
        return text

    return translate